def clean_item(it):
    if isinstance(it.get("a"), str):
        for noise in TAIL_NOISE:
            if it["a"].endswith(noise):
                it["a"] = it["a"][:-len(noise)].rstrip()
    if isinstance(it.get("e"), str):
        e = it["e"].strip()
        if e.startswith("解析："):
            e = e[3:].strip()
        if e.startswith("解析:"):
            e = e[3:].strip()
        it["e"] = e
    if it.get("id") in EXTRA and not it.get("e"):
        it["e"] = EXTRA[it["id"]]
    # 只有「正确答案为X（……）」一句的选择题，用重写版覆盖
    if it.get("id") in SHORT:
        it["e"] = SHORT[it["id"]]
    return it


def apply_explain(items):
    """给 items 补详解并清理脏数据，返回详解有变动的条数。"""
    changed = 0
    for it in items:
        before = it.get("e") or ""
        clean_item(it)
        if (it.get("e") or "") != before:
            changed += 1
    return changed


